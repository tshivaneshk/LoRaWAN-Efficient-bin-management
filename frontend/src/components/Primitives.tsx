/**
 * StatusBadge (Section 5):
 * Always encodes status by color + icon + text (never color alone).
 */
export const StatusBadge: React.FC<{
  status: BinStatus | 'OFFLINE';
  suspect?: boolean;
  size?: 'sm' | 'md';
}> = ({ status, suspect = false, size = 'md' }) => {
  const sizeClasses =
    size === 'sm' ? 'px-1.5 py-0.5 text-[11px] gap-1' : 'px-2 py-0.5 text-xs gap-1.5';

  if (status === 'OFFLINE') {
    return (
      <span
        className={`inline-flex items-center rounded font-mono font-medium border border-dashed border-[var(--status-offline)] bg-[var(--status-offline)]/15 text-[var(--status-offline)] ${sizeClasses}`}
      >
        <WifiOff className="w-3 h-3 shrink-0" />
        <span>OFFLINE</span>
      </span>
    );
  }

  if (status === 'FULL') {
    return (
      <span
        className={`inline-flex items-center rounded font-mono font-semibold border border-[var(--status-full)] bg-[var(--status-full)]/15 text-[var(--status-full)] animate-full-alert ${sizeClasses}`}
      >
        <Flame className="w-3 h-3 shrink-0" />
        <span>{suspect ? 'FULL (SUSPECT)' : 'FULL'}</span>
      </span>
    );
  }

  if (status === 'HIGH') {
    return (
      <span
        className={`inline-flex items-center rounded font-mono font-medium border border-[var(--status-high)] bg-[var(--status-high)]/15 text-[var(--status-high)] ${sizeClasses}`}
      >
        <AlertTriangle className="w-3 h-3 shrink-0" />
        <span>HIGH</span>
      </span>
    );
  }

  if (status === 'FILLING') {
    return (
      <span
        className={`inline-flex items-center rounded font-mono font-medium border border-[var(--status-filling)] bg-[var(--status-filling)]/15 text-[var(--status-filling)] ${sizeClasses}`}
      >
        <ArrowUpRight className="w-3 h-3 shrink-0" />
        <span>FILLING</span>
      </span>
    );
  }

  return (
    <span
      className={`inline-flex items-center rounded font-mono font-medium border border-[var(--status-normal)] bg-[var(--status-normal)]/15 text-[var(--status-normal)] ${sizeClasses}`}
    >
      <CheckCircle2 className="w-3 h-3 shrink-0" />
      <span>NORMAL</span>
    </span>
  );
};

export const RadialGauge: React.FC<{
  valuePct: number;
  status: BinStatus | 'OFFLINE';
  size?: number;
  strokeWidth?: number;
  showLabel?: boolean;
}> = ({ valuePct, status, size = 84, strokeWidth = 7, showLabel = true }) => {
  const radius = (size - strokeWidth) / 2;
  const circumference = 2 * Math.PI * radius;
  const clamped = Math.min(100, Math.max(0, valuePct));
  const offset = circumference - (clamped / 100) * circumference;

  const colorVar =
    status === 'OFFLINE'
      ? 'var(--status-offline)'
      : status === 'FULL'
        ? 'var(--status-full)'
        : status === 'HIGH'
          ? 'var(--status-high)'
          : status === 'FILLING'
            ? 'var(--status-filling)'
            : 'var(--status-normal)';

  return (
    <div
      className="relative inline-flex items-center justify-center"
      style={{ width: size, height: size }}
    >
      <svg width={size} height={size} className="-rotate-90">
        <circle
          cx={size / 2}
          cy={size / 2}
          r={radius}
          fill="transparent"
          stroke="var(--surface-3)"
          strokeWidth={strokeWidth}
        />
        <circle
          cx={size / 2}
          cy={size / 2}
          r={radius}
          fill="transparent"
          stroke={colorVar}
          strokeWidth={strokeWidth}
          strokeDasharray={circumference}
          strokeDashoffset={offset}
          strokeLinecap="round"
          className="transition-all duration-250 ease-out"
        />
      </svg>
      {showLabel && (
        <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
          <span className="font-mono text-lg font-semibold tabular-nums text-[var(--text)]">
            {Math.round(clamped)}%
          </span>
          <span className="text-[10px] uppercase tracking-wider text-[var(--text-muted)]">
            FILL
          </span>
        </div>
      )}
    </div>
  );
};

