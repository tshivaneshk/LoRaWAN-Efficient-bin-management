export const Sparkline: React.FC<{
  data: number[];
  width?: number;
  height?: number;
  color?: string;
  dashed?: boolean;
}> = ({ data, width = 140, height = 32, color = 'var(--accent)', dashed = false }) => {
  if (data.length < 2) {
    return (
      <div
        className="flex items-center justify-center text-[10px] font-mono text-[var(--text-faint)] border border-dashed border-[var(--border)] rounded"
        style={{ width, height }}
      >
        awaiting samples
      </div>
    );
  }
  const min = Math.min(...data);
  const max = Math.max(...data);
  const range = Math.max(1, max - min);

  const pts = data
    .map((val, i) => {
      const x = (i / (data.length - 1)) * (width - 4) + 2;
      const y = height - 4 - ((val - min) / range) * (height - 8);
      return `${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(' ');

  return (
    <svg width={width} height={height} className="overflow-visible">
      <polyline
        fill="none"
        stroke={color}
        strokeWidth={1.75}
        strokeDasharray={dashed ? '3 2' : undefined}
        points={pts}
      />
    </svg>
  );
};

