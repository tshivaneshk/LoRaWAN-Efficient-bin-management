/**
 * ProvenanceBadge (Section 2):
 * - SIMULATED: violet dashed outline, small caps, mono font.
 * - LIVE HARDWARE: solid green dot with pulse, shown only for data arriving from the real prototype.
 * - SIMULATED_DEMO: violet dashed outline with (DEMO) label.
 */
export const ProvenanceBadge: React.FC<{
  provenance: Provenance;
  compact?: boolean;
}> = ({ provenance, compact = false }) => {
  if (provenance === 'LIVE_HARDWARE') {
    return (
      <span
        className="inline-flex items-center gap-1.5 rounded px-1.5 py-0.5 font-mono text-[10px] font-medium tracking-wider uppercase border border-[var(--live)] bg-[var(--live)]/10 text-[var(--live)]"
        title="Telemetry received from physical Arduino Nano + LoRa prototype"
      >
        <span className="h-1.5 w-1.5 rounded-full bg-[var(--live)] animate-live-dot" />
        {compact ? 'LIVE' : 'LIVE HARDWARE'}
      </span>
    );
  }

  const label =
    provenance === 'SIMULATED_DEMO'
      ? compact
        ? 'SIM (DEMO)'
        : 'SIMULATED (DEMO)'
      : compact
        ? 'SIM'
        : 'SIMULATED';

  return (
    <span
      className="inline-flex items-center gap-1 rounded px-1.5 py-0.5 font-mono text-[10px] font-medium tracking-wider uppercase border border-dashed border-[var(--sim)] bg-[var(--sim)]/10 text-[var(--sim)]"
      title="Generated by deterministic physical + RF simulation engine"
    >
      {label}
    </span>
  );
};

